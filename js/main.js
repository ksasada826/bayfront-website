function setNavOpen(open) {
  siteNav.classList.toggle("is-open", open);
  navToggle.setAttribute("aria-expanded", open ? "true" : "false");
  navToggle.setAttribute(
    "aria-label",
    open
      ? (lang === "en" ? "Close menu" : "メニューを閉じる")
      : (lang === "en" ? "Open menu" : "メニューを開く")
  );
}

function currentDict() {
  return lang === "en" ? en : ja;
}

function setFormHint(text, state) {
  if (!formHint) return;
  formHint.textContent = text || "";
  formHint.classList.remove("is-error", "is-ok");
  if (state === "error") formHint.classList.add("is-error");
  if (state === "ok") formHint.classList.add("is-ok");
}

function applyCopy() {
  const dict = currentDict();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });
  const spans = langToggle.querySelectorAll("span");
  spans[0].className = lang === "en" ? "on" : "off";
  spans[1].className = lang === "ja" ? "on" : "off";
  document.documentElement.lang = lang;
  document.title = META[lang].title;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", META[lang].description);
  if (formHint && !formHint.classList.contains("is-error") && !formHint.classList.contains("is-ok")) {
    formHint.textContent = dict["form.hint"];
  }
  setNavOpen(siteNav.classList.contains("is-open"));
}

function formAccessKey() {
  const cfg = window.BAYFRONT_FORM || {};
  return (cfg.accessKey || "").trim();
}

langToggle.addEventListener("click", () => {
  lang = lang === "ja" ? "en" : "ja";
  try { localStorage.setItem(LANG_KEY, lang); } catch (_e) { /* ignore */ }
  applyCopy();
});

navToggle.addEventListener("click", (e) => {
  e.stopPropagation();
  setNavOpen(!siteNav.classList.contains("is-open"));
});

navLinks.querySelectorAll("a").forEach((a) => {
  a.addEventListener("click", () => setNavOpen(false));
});

document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") setNavOpen(false);
});

document.addEventListener("click", (e) => {
  if (!siteNav.classList.contains("is-open")) return;
  if (!siteNav.contains(e.target)) setNavOpen(false);
});

if (contactForm) {
  contactForm.addEventListener("submit", async (e) => {
    e.preventDefault();
    const dict = currentDict();
    const key = formAccessKey();
    if (!key) {
      setFormHint(dict["form.needKey"], "error");
      return;
    }
    if (!contactForm.reportValidity()) return;

    const submitBtn = contactForm.querySelector('button[type="submit"]');
    if (submitBtn) submitBtn.disabled = true;
    setFormHint(dict["form.sending"], null);

    const fd = new FormData(contactForm);
    const payload = {
      access_key: key,
      subject: "Bayfront Partners — website inquiry",
      from_name: "Bayfront Partners site",
      name: String(fd.get("name") || "").trim(),
      email: String(fd.get("email") || "").trim(),
      company: String(fd.get("company") || "").trim(),
      message: String(fd.get("message") || "").trim(),
      botcheck: fd.get("botcheck") ? true : false
    };

    try {
      const res = await fetch("https://api.web3forms.com/submit", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Accept: "application/json"
        },
        body: JSON.stringify(payload)
      });
      const data = await res.json().catch(() => ({}));
      if (res.ok && data.success) {
        contactForm.reset();
        setFormHint(dict["form.ok"], "ok");
      } else {
        setFormHint(dict["form.err"], "error");
      }
    } catch (_err) {
      setFormHint(dict["form.err"], "error");
    } finally {
      if (submitBtn) submitBtn.disabled = false;
    }
  });
}

applyCopy();
